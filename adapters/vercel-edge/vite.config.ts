// ---------------------------------------------------------------------------
// adapters/vercel-edge/vite.config.ts — SERVER (pre-render) build for Vercel.
//
// WHY THIS FILE EXISTS:
//   `qwik build` runs TWO builds: build.client (vite.config.ts -> browser JS)
//   and build.server (THIS file -> HTML pre-render). Vercel's `npm run build`
//   needs build.server to exist or it fails with
//   `"build.server" script not found in package.json`.
//   NOTE: despite the folder name, this currently uses staticAdapter(), NOT
//   vercelEdgeAdapter(). The site has no server$/loaders needing per-request
//   compute, so pages are pre-rendered to dist/index.html at build time and
//   Vercel serves them as static files. If you later add form actions or
//   authenticated loaders, swap staticAdapter -> vercelEdgeAdapter and add
//   src/entry.vercel-edge.tsx as a rollup input.
// ---------------------------------------------------------------------------
import { staticAdapter } from "@builder.io/qwik-city/adapters/static/vite";
// JUNIOR NOTE: extendConfig() merges this adapter config ON TOP of the base
// vite.config.ts, so plugins (qwikCity/qwikVite) are inherited, not repeated.
import { extendConfig } from "@builder.io/qwik-city/vite";
// AI NOTE: relative import reaches the repo-root config from adapters/*/.
import baseConfig from "../../vite.config";

export default extendConfig(baseConfig, () => {
  return {
    build: {
      // ssr:true tells Vite to build for Node (server) instead of the browser:
      // no window/document shims, externalizes node built-ins.
      ssr: true,
      rollupOptions: {
        // "@qwik-city-plan" is a VIRTUAL module generated by qwikCity() — it is
        // the route manifest (which files map to which URLs). It exists only at
        // build time; do not look for it on disk.
        input: ["@qwik-city-plan"],
      },
    },
    plugins: [
      staticAdapter({
        // Used for absolute URLs in sitemap.xml + canonical tags.
        // CHANGE THIS to the real production domain before launch.
        origin: "https://businesstemplate.vercel.app",
      }),
    ],
  };
});
